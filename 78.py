# Считываем самое первое слово
prev_word = input("Введите слово: ")

while True:
    current_word = input("Введите следующее слово: ")
    
    # Если последняя буква предыдущего не совпала с первой буквой текущего
    if prev_word[-1] != current_word[0]:
        print(current_word)  # Выводим слово-нарушитель
        break                # И выходим из цикла
        
    # Если совпало — текущее слово становится предыдущим для следующего шага
    prev_word = current_word