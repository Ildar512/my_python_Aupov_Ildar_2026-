n = int(input("Сколько строк будет введено? "))

# Создаём список нужного размера, чтобы расставить буквы по местам
word_parts = [""] * n

for i in range(n):
    # Считываем строку и разбиваем её по пробелу
    pos_str, char = input("Введите позицию и букву: ").split()
    
    # Превращаем позицию в число и вычитаем 1 (индексация с 0)
    pos = int(pos_str) - 1
    
    # Ставим букву на своё место в списке
    word_parts[pos] = char

# Склеиваем список в одну строку
print("".join(word_parts))