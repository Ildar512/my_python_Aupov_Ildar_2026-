n = int(input("Сколько пар чисел будет введено? "))

for i in range(n):
    # Считываем строку и сразу разбиваем её на два числа по пробелу
    a_str, b_str = input("Введите пару чисел: ").split()
    
    # Превращаем строки в целые числа
    a = int(a_str)
    b = int(b_str)
    
    # Сравниваем и выводим в нужном порядке
    if a < b:
        print(a, b)
    else:
        print(b, a)  # Если a больше или равно b, выводим b первым